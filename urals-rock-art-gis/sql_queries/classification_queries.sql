-- ============================================================
-- SQL-запросы для классификации археологических памятников
-- Проект: Пространственный анализ наскального искусства Урала
-- Инструмент: QGIS (Field Calculator / Virtual Layer)
-- ============================================================

-- ------------------------------------------------------------
-- 1. Классификация писаниц по эпохам
-- Поля-флаги: Мезолит_int, Неолит_int, Энеолит_int, 
--   Эпоха развитой бронзы_int, Ранний железный век_int, Эпоха средневековья_int
-- ------------------------------------------------------------
CASE 
    WHEN "Мезолит_int" = 1 THEN 'Мезолит'
    WHEN "Неолит_int" = 1 THEN 'Неолит'
    WHEN "Энеолит_int" = 1 THEN 'Энеолит'
    WHEN "Эпоха развитой бронзы_int" = 1 THEN 'Бронзовый век'
    WHEN "Ранний железный век_int" = 1 THEN 'Ранний железный век'
    WHEN "Эпоха средневековья_int" = 1 THEN 'Средневековье'
    ELSE 'Не атрибутировано'
END

-- ------------------------------------------------------------
-- 2. Классификация иных археологических памятников по эпохам
-- Поля: Мезолит_int, Неолит_int, Энеолит_int, Эпоха_развитой_бронзы_int,
--   Ранний_железный_век_int, Эпоха_средневековья_int
-- ------------------------------------------------------------
CASE 
    WHEN "Мезолит_int" = 1 THEN 'Мезолит'
    WHEN "Неолит_int" = 1 THEN 'Неолит'
    WHEN "Энеолит_int" = 1 THEN 'Энеолит'
    WHEN "Эпоха_развитой_бронзы_int" = 1 THEN 'Бронза'
    WHEN "Ранний_железный_век_int" = 1 THEN 'Ранний железный'
    WHEN "Эпоха_средневековья_int" = 1 THEN 'Средневековье'
    ELSE 'Не определена'
END

-- ------------------------------------------------------------
-- 3. Классификация всех памятников по археологическим культурам (25 групп)
-- Поля: культ_шигирская, культ_боборыкинская, культ_горбуновская, ...
-- ------------------------------------------------------------
CASE
    WHEN "культ_шигирская" = 1 THEN 'Шигирская (мезолит–неолит)'
    WHEN "культ_боборыкинская" = 1 THEN 'Боборыкинская (неолит)'
    WHEN "культ_горбуновская" = 1 THEN 'Горбуновская (неолит)'
    WHEN "культ_ямочно_гребенчатой" = 1 THEN 'Ямочно-гребенчатой керамики (неолит)'
    WHEN "культ_андреевская" = 1 THEN 'Андреевская (энеолит)'
    WHEN "культ_аятская" = 1 THEN 'Аятская (энеолит)'
    WHEN "культ_липчинская" = 1 THEN 'Липчинская (энеолит)'
    WHEN "культ_бархатовская" = 1 THEN 'Бархатовская (энеолит–бронза)'
    WHEN "культ_андроновская" = 1 THEN 'Андроновская (развитая бронза)'
    WHEN "культ_коптяковская" = 1 THEN 'Коптяковская (развитая бронза)'
    WHEN "культ_черкаскульская" = 1 THEN 'Черкаскульская (развитая бронза)'
    WHEN "культ_межовская" = 1 THEN 'Межовская (развитая бронза)'
    WHEN "культ_предкоптяковская" = 1 THEN 'Предкоптяковская (развитая бронза)'
    WHEN "культ_ананьинская" = 1 THEN 'Ананьинская (ранний железный)'
    WHEN "культ_гамаюнская" = 1 THEN 'Гамаюнская (ранний железный)'
    WHEN "культ_иткульская" = 1 THEN 'Иткульская (ранний железный)'
    WHEN "культ_исетская" = 1 THEN 'Исетская (ранний железный)'
    WHEN "культ_сарматская" = 1 THEN 'Сарматская (ранний железный)'
    WHEN "культ_макушинская" = 1 THEN 'Макушинская (бронза–железо)'
    WHEN "культ_молчановская" = 1 THEN 'Молчановская (ранний железный–средневековье)'
    WHEN "культ_усть_полуйская" = 1 THEN 'Усть-полуйская (ранний железный–средневековье)'
    WHEN "культ_петрогромская" = 1 THEN 'Петрогромская (ранний железный)'
    WHEN "культ_юдинская" = 1 THEN 'Юдинская (средневековье)'
    WHEN "культ_ломоватовская" = 1 THEN 'Ломоватовская (средневековье)'
    WHEN "культ_родановская" = 1 THEN 'Родановская (средневековье)'
    ELSE 'Прочие культуры / не указана'
END